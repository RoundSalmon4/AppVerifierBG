/**
 * The package name is the app's package name.
 *
 * The hashesList is a list of Hashes, which itself contains a list of hashes.
 *
 * The hasMultipleSigners (the true or false) is whether it has multiple signers or not.
 * hasMultipleSigners can be viewed from the app by turning on the relevant setting.
 *
 * There should be one Hashes for each signing configuration an app has.
 * The Hashes has a sources value.
 * For example, if those Hashes are from both GitHub and the Google Play Store (you checked and both have the same
 * hashes),
 * then the database entry would be:
 *
 * ```
 * InternalDatabaseVerificationInfo(
 *     "com.example.app",
 *     listOf(
 *         Hashes(
 *             listOf(
 *                 Source.GITHUB,
 *                 Source.GOOGLE_PLAY_STORE
 *             ),
 *             listOf(
 *                 "SOME HASH HERE",
 *                 "ANOTHER HASH HERE"
 *             ),
 *             false
 *         )
 *     )
 * ),
 * ```
 *
 * If for example the Google Play Store one has different hashes then it gets its own Hashes
 * with sources that has only Google Play Store like below:
 *
 * ```
 * InternalDatabaseVerificationInfo(
 *     "com.example.app",
 *     listOf(
 *         Hashes(
 *             listOf(
 *                 Source.GITHUB
 *             ),
 *             listOf(
 *                 "SOME HASH HERE",
 *                 "ANOTHER HASH HERE"
 *             ),
 *             false
 *         )
 *         Hashes(
 *             listOf(
 *                 Source.GOOGLE_PLAY_STORE
 *             ),
 *             listOf(
 *                 "SOME DIFFERENT HASH HERE",
 *                 "ANOTHER DIFFERENT HASH HERE"
 *             ),
 *             false
 *         )
 *     )
 * ),
 * ```
 */
data class InternalDatabaseVerificationInfo(
    val packageName: String,
    val hashesList: List<Hashes>
)

